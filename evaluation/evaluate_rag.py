import os
import time
import faiss
import numpy as np
from sentence_transformers import SentenceTransformer
import ollama
import config
from sklearn.metrics.pairwise import cosine_similarity  # For cosine similarity
from rouge_score import rouge_scorer  # For ROUGE score


# Load the sentence-transformers embedding model
embedder = SentenceTransformer(config.EMBEDDING_MODEL)

# Load FAISS index in memory
faiss_index_cache = None

def load_faiss_index(index_path=config.VECTOR_STORE_PATH):
    """
    Loads the FAISS index from the specified file path. Caches the index in memory.
    """
    global faiss_index_cache
    if faiss_index_cache is None:
        faiss_index_cache = faiss.read_index(index_path)
    return faiss_index_cache

def load_combined_question_answer_texts(chunk_dir=config.CHUNK_DATA_PATH):
    """
    Loads the combined question-answer texts from the specified directory.

    Returns:
        list: A list of combined question-answer texts.
    """
    combined_texts = []
    try:
        chunk_files = [f for f in os.listdir(chunk_dir) if f.startswith("chunk_") and f.endswith(".txt")]
        for chunk_file in chunk_files:
            chunk_path = os.path.join(chunk_dir, chunk_file)
            with open(chunk_path, "r", encoding="utf-8") as f:
                combined_text = f.read().strip()
                combined_texts.append(combined_text)
    except Exception as e:
        raise Exception(f"Error loading combined question-answer texts: {e}")
    
    return combined_texts

def retrieve_top_k_chunks(query, index, combined_data, k=5, distance_threshold=35):
    """
    Retrieves the top-k most relevant combined question-answer chunks from the FAISS index based on the query.
    """
    query_embedding = embedder.encode([query], convert_to_numpy=True)
    distances, indices = index.search(query_embedding, k)

    top_chunks = []
    for i, distance in enumerate(distances[0]):
        if distance < distance_threshold:  # Filter based on distance threshold
            top_chunks.append(combined_data[indices[0][i]])

    return top_chunks

def filter_relevant_chunks(query, chunks):
    """
    Filters the chunks to keep only the one that is most relevant to the query.
    """
    query_keywords = set(query.lower().split())
    best_chunk = None
    best_match_count = 0

    for chunk in chunks:
        chunk_keywords = set(chunk.lower().split())
        match_count = len(query_keywords.intersection(chunk_keywords))

        # Update best chunk if the current one has more matches
        if match_count > best_match_count:
            best_match_count = match_count
            best_chunk = chunk

    # Return the best chunk if found, otherwise an empty list
    return [best_chunk] if best_chunk else []

def generate_response(query, context_chunks):
    """
    Generates a response to the user's query using Mistral via Ollama with provided context (retrieved chunks).
    """
    if not context_chunks:
        return "Sorry, I don't have information about that. Please ask another question."

    # Use the top relevant chunks for context (you can use more chunks if needed)
    context = "\n".join(context_chunks[:2])  # Taking top 2 chunks for context

    # Create a prompt combining the retrieved chunks (context) and the user's query
    prompt = f""" 
    You are Helpbee, designed to respond to customer questions. You are a helpful assistant and polite. Based on the context information, provide a concise response in a paragraph.

    Context: {context}

    Question: {query}
    """

    # Use Ollama to generate the response
    response = ollama.generate(model=config.MODEL_NAME, prompt=prompt)
    
    # Return the generated response
    return response['response']

def evaluate_faithfulness_cosine_similarity(retrieved_chunks, generated_response):
    """
    Evaluates the faithfulness of the generated response by comparing it to the retrieved chunks using Cosine Similarity.
    
    Args:
        retrieved_chunks (list): List of retrieved chunks used as context.
        generated_response (str): The response generated by the model.
    
    Returns:
        float: The average cosine similarity score between the generated response and the retrieved chunks.
    """
    if not retrieved_chunks or not generated_response:
        print("No retrieved chunks or generated response is empty.")
        return 0.0  # Return a score of 0 for faithfulness if no chunks or response

    # Embed the retrieved chunks and the generated response
    chunk_embeddings = embedder.encode(retrieved_chunks, convert_to_numpy=True)
    response_embedding = embedder.encode([generated_response], convert_to_numpy=True)

    # Ensure the embeddings are 2D arrays before computing cosine similarity
    if response_embedding.ndim == 1:
        response_embedding = response_embedding.reshape(1, -1)  # Reshape to (1, n)
    if chunk_embeddings.ndim == 1:
        chunk_embeddings = chunk_embeddings.reshape(1, -1)  # Reshape to (1, n)

    # Check if there are valid chunk embeddings
    if chunk_embeddings.size == 0:
        print("Chunk embeddings are empty.")
        return 0.0

    # Calculate cosine similarities
    similarities = cosine_similarity(response_embedding, chunk_embeddings)

    # Return the average cosine similarity score
    return np.mean(similarities)

def evaluate_rogue_faithfulness(retrieved_chunks, generated_response):
    """
    Evaluates the faithfulness of the generated response by comparing it to the retrieved chunks using ROUGE score.
    
    Args:
        retrieved_chunks (list): List of retrieved chunks used as context.
        generated_response (str): The response generated by the model.
    
    Returns:
        dict: A dictionary containing the ROUGE scores for faithfulness evaluation.
    """
    # Combine retrieved chunks into a single reference text
    reference_text = " ".join(retrieved_chunks)

    # Initialize ROUGE scorer
    scorer = rouge_scorer.RougeScorer(['rougeL'], use_stemmer=True)

    # Compute ROUGE scores between reference and generated response
    scores = scorer.score(reference_text, generated_response)

    return scores

def evaluate_answer_relevance(query, generated_response):
    """
    Evaluates the relevance of the generated response by calculating the cosine similarity
    between the query and the generated response.
    
    Args:
        query (str): The user's original question.
        generated_response (str): The response generated by the model.
    
    Returns:
        float: Cosine similarity score between query and response (0 to 1).
    """
    # Create embeddings for both the query and the generated response
    query_embedding = embedder.encode([query], convert_to_numpy=True)
    response_embedding = embedder.encode([generated_response], convert_to_numpy=True)

    # Compute cosine similarity
    relevance_score = cosine_similarity(query_embedding, response_embedding).item()
    
    return relevance_score

def calculate_cosine_similarity(context_chunks, generated_response):
    """
    Measures the Context Precision by calculating the cosine similarity
    between the embeddings of the retrieved context and the generated response.
    """
    context_embeddings = embedder.encode(context_chunks, convert_to_numpy=True)
    response_embedding = embedder.encode([generated_response], convert_to_numpy=True)

    similarities = cosine_similarity(response_embedding, context_embeddings)
    avg_similarity = np.mean(similarities)
    
    return avg_similarity

